// The market index: one URL, one document, and the two local copies a read can
// fall back to (the degradation chain is spelled out in readIndex).
//
// The URL names a FIXED tag (`market`) rather than `latest`: `latest` is the
// product release — a deb, a dmg, an apk — and this asset must not ride on it,
// or every host release would be the index and every index bump a release. The
// workflow that publishes it (.github/workflows/market.yml) is the same shape:
// push to `market/**`, tag `market`, asset `index.json`.
const INDEX_URL = "https://github.com/Ethereal1024/Clutch/releases/download/market/index.json";
const INDEX_SCHEMA = 2;
const SNAPSHOT_FILE = path.join(__dirname, "market.snapshot.json"); // shipped, refreshed at release
const INDEX_CACHE = path.join(os.homedir(), ".clutch", "market", "index.json"); // this machine's last good read
const MANIFEST_SCHEMA = 1; // a module's own release manifest (unchanged by the index)
const ID_RE = /^[A-Za-z0-9][A-Za-z0-9._-]*\/[A-Za-z0-9][A-Za-z0-9._-]*$/; // <owner>/<name>

const SKIP_DIRS = new Set([".git", ".venv", "__pycache__", ".pytest_cache", ".ruff_cache", "node_modules"]);

